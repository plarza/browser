/// Bangs: `!w octopus` or `octopus !w` goes straight to that site's search.
/// Core's own table, matched here; nothing is fetched to resolve one, and a
/// bang works with or without a search engine set. `%s` is where the words
/// go; a bang on its own goes to the site's front page.
public enum Bangs {
    public struct Bang {
        public let search: String
        public let home: String
    }

    public static func resolve(_ typed: String) -> URL? {
        var words = typed.split(separator: " ", omittingEmptySubsequences: true).map(String.init)
        guard let index = words.firstIndex(where: { $0.count > 1 && $0.hasPrefix("!") }) ?? words.firstIndex(where: { $0.count > 1 && $0.hasSuffix("!") && $0.first != "!" }),
              index == 0 || index == words.count - 1
        else { return nil }
        let token = words[index]
        let key = (token.hasPrefix("!") ? String(token.dropFirst()) : String(token.dropLast())).lowercased()
        guard let bang = table[key] else { return nil }
        words.remove(at: index)
        let query = words.joined(separator: " ")
        if query.isEmpty { return URL(string: bang.home) }
        return Address.search(query, template: bang.search)
    }

    private static func b(_ search: String, _ home: String? = nil) -> Bang {
        let home = home ?? {
            guard let url = URL(string: search.replacingOccurrences(of: "%s", with: "")),
                  let scheme = url.scheme, let host = url.host
            else { return search }
            return "\(scheme)://\(host)/"
        }()
        return Bang(search: search, home: home)
    }

